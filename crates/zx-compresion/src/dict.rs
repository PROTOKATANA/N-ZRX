/// Diccionario de transacciones de la red dev, construido una sola vez.
static DICCIONARIO_TX: OnceLock<Diccionario> = OnceLock::new();

/// El diccionario de transacciones de la red dev.
#[must_use]
pub fn diccionario_tx() -> &'static Diccionario {
    DICCIONARIO_TX.get_or_init(|| Diccionario {
        id: DICT_ID_TX,
        bytes: DICT_TX_BYTES.to_vec(),
    })
}

/// El diccionario de una versión, o `None` si no se conoce.
#[must_use]
pub fn diccionario(id: u32) -> Option<&'static Diccionario> {
    if id == DICT_ID_TX {
        Some(diccionario_tx())
    } else {
        None
    }
}
