//! Diccionarios zstd de ZRX-C.
//!
//! Un diccionario entrenado con datos reales del mismo tipo mejora mucho los
//! mensajes pequeños (transacciones, votos). El diccionario se identifica con un
//! `id` distinto de cero y sus bytes viajan versionados con la red: cambiar el
//! diccionario cambia los bytes comprimidos, así que el marco guarda el `dict_id`
//! para rechazar marcos comprimidos con otro diccionario.
//!
//! La crate concentra aquí el diccionario de transacciones de la red dev, que
//! antes vivía duplicado en `zx-p2p::zrxc`.

use std::sync::OnceLock;

use crate::error::ErrorCompresion;

/// Identificador de la versión del diccionario de transacciones (`ZRC` + versión 1).
pub const DICT_ID_TX: u32 = 0x5A52_4301;

/// Un diccionario zstd con su identificador de versión.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Diccionario {
    pub(crate) id: u32,
    pub(crate) bytes: Vec<u8>,
}

impl Diccionario {
    /// Crea un diccionario a partir de sus bytes ya conocidos.
    ///
    /// # Errores
    /// [`ErrorCompresion::DiccionarioIdCero`] si `id` es `0`, reservado para
    /// «sin diccionario».
    pub fn nuevo(id: u32, bytes: Vec<u8>) -> Result<Self, ErrorCompresion> {
        if id == 0 {
            return Err(ErrorCompresion::DiccionarioIdCero);
        }
        Ok(Self { id, bytes })
    }

    /// Entrena un diccionario con `muestras`, de como mucho `max_bytes`.
    ///
    /// # Errores
    /// [`ErrorCompresion::DiccionarioIdCero`] si `id` es `0`;
    /// [`ErrorCompresion::Entrenamiento`] si zstd no puede entrenar con las
    /// muestras dadas.
    pub fn entrenar(
        id: u32,
        muestras: &[Vec<u8>],
        max_bytes: usize,
    ) -> Result<Self, ErrorCompresion> {
        if id == 0 {
            return Err(ErrorCompresion::DiccionarioIdCero);
        }
        let bytes = zstd::dict::from_samples(muestras, max_bytes)
            .map_err(|e| ErrorCompresion::Entrenamiento(e.to_string()))?;
        Ok(Self { id, bytes })
    }

    /// El identificador de versión del diccionario.
    #[must_use]
    pub fn id(&self) -> u32 {
        self.id
    }

    /// Los bytes del diccionario.
    #[must_use]
    pub fn bytes(&self) -> &[u8] {
        &self.bytes
    }
}

